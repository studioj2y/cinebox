def build():
    questions = []
    for i, (cat, q, opts) in enumerate(RAW, 1):
        options = []
        for label, tags in opts:
            weights = {}
            for t in tags:
                weights[t] = weights.get(t, 0) + 1
            options.append({"text": label, "weights": weights})
        questions.append({
            "id": i,
            "category": cat,
            "question": q,
            "options": options,
        })
    return questions

def main():
    qs = build()
    OUT.parent.mkdir(parents=True, exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("// 自动生成，请勿手改。运行 scripts/gen_questions.py 重新生成。\n")
        f.write("window.QUESTIONS = ")
        json.dump(qs, f, ensure_ascii=False, indent=1)
        f.write(";\n")
    print(f"已生成 {len(qs)} 道题 -> {OUT}")

if __name__ == "__main__":
    main()
